// 根据羁绊名称获取羁绊详情
export const getSynergyByName = (name) => {
  // 清理羁绊名称（去除数字和空格）
  const cleanName = name.replace(/[0-9]/g, '').trim()
  
  // 搜索特质羁绊
  if (synergiesData.traits[cleanName]) {
    return synergiesData.traits[cleanName]
  }
  
  // 搜索职业羁绊
  if (synergiesData.classes[cleanName]) {
    return synergiesData.classes[cleanName]
  }
  
  return null
}

// 根据羁绊名称和数量获取具体效果
export const getSynergyEffect = (name, count) => {
  const synergy = getSynergyByName(name)
  if (!synergy) return null
  
  const level = synergy.levels.find(l => l.count === count)
  return level ? level.effect : null
}
