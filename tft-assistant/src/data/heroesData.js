// 根据英雄名称获取图标URL
export const getHeroIcon = (heroName) => {
  const hero = heroesData[heroName]
  return hero ? hero.icon : '/images/default-hero.png'
}

// 获取所有英雄名称列表
export const getHeroNames = () => Object.keys(heroesData)

// 获取所有英雄数据
export const getAllHeroes = () => heroesData

// 导出所有英雄列表
export const allHeroes = Object.values(heroesData)

// 按费用分组
export const heroesByCost = {
  1: allHeroes.filter(h => h.cost === 1),
  2: allHeroes.filter(h => h.cost === 2),
  3: allHeroes.filter(h => h.cost === 3),
  4: allHeroes.filter(h => h.cost === 4),
  5: allHeroes.filter(h => h.cost === 5)
}

// 根据羁绊获取英雄
export const getHeroesBySynergy = (synergyName) => {
  return allHeroes.filter(hero => hero.synergies.includes(synergyName))
}

// 根据英文名获取英雄
export const getHeroByEnglishName = (englishName) => {
  return Object.values(heroesData).find(hero => hero.englishName === englishName)
}
